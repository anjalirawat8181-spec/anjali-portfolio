import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const dir = 'src/data'
const found = new Map()
for (const f of readdirSync(dir).filter((x) => x.endsWith('.ts'))) {
  readFileSync(join(dir, f), 'utf8')
    .split('\n')
    .forEach((line, i) => {
      for (const m of line.matchAll(/TODO_[A-Z0-9_]+/g)) {
        if (!found.has(m[0])) found.set(m[0], `${dir}/${f}:${i + 1}`)
      }
    })
}
const rows = [...found].map(([k, where]) => `- [ ] \`${k}\` — ${where}`)
const body = `# Missing links

Auto-generated by \`npm run build\` (scripts/missing-links.mjs). Replace each placeholder in the file shown,
and it will disappear from this list. Until then the site shows it as a disabled "Link coming soon" chip.

${rows.length ? rows.join('\n') : 'None. Everything is filled in.'}
`
writeFileSync('MISSING_LINKS.md', body)
console.log(`MISSING_LINKS.md: ${rows.length} placeholder(s)`)
